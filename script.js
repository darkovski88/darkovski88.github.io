const appsGrid = document.querySelector("#apps-grid");
const statTotal = document.querySelector("#stat-total");
const statAndroid = document.querySelector("#stat-android");
const statIos = document.querySelector("#stat-ios");
const syncDate = document.querySelector("#sync-date");
const yearNode = document.querySelector("#year");
const revealNodes = Array.from(document.querySelectorAll(".reveal"));

const formatSyncDate = () => {
  const date = new Date();
  return date.toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
};

const getAvailabilityText = (app) => {
  if (app.iosUrl) {
    return "Available on Android and iOS";
  }
  return "Available on Android";
};

const renderApps = () => {
  if (!appsGrid) {
    return;
  }

  appsGrid.innerHTML = apps
    .map((app, index) => {
      const iosButton = app.iosUrl
        ? `<a class="store-link ios" href="${app.iosUrl}" target="_blank" rel="noreferrer">Open on App Store</a>`
        : "";

      const screenshots = app.screenshots
        .map(
          (url, shotIndex) =>
            `<a class="shot-link" href="${url}" target="_blank" rel="noreferrer"><img src="${url}" alt="${app.name} screenshot ${
              shotIndex + 1
            }" loading="lazy" /></a>`
        )
        .join("");

      return `
        <article class="app-showcase">
          <div class="card-top">
            <span class="category-chip">${app.category}</span>
            <span class="status-chip">Public #${index + 1}</span>
          </div>
          <h3>${app.name}</h3>
          <p class="card-copy">${app.description}</p>
          <p class="platform-line">${getAvailabilityText(app)}</p>
          <div class="cta-list">
            <a class="store-link android" href="${app.androidUrl}" target="_blank" rel="noreferrer">Open on Google Play</a>
            ${iosButton}
          </div>
          <div class="screenshot-carousel" data-carousel>
            <button class="carousel-btn prev" type="button" aria-label="Previous screenshots">
              &#8249;
            </button>
            <div class="screenshot-track">
              ${screenshots}
            </div>
            <button class="carousel-btn next" type="button" aria-label="Next screenshots">
              &#8250;
            </button>
          </div>
        </article>
      `;
    })
    .join("");
};

const setupCarousels = () => {
  const carousels = Array.from(document.querySelectorAll("[data-carousel]"));
  const scheduleUpdate = window.requestAnimationFrame
    ? (callback) => window.requestAnimationFrame(callback)
    : (callback) => callback();

  carousels.forEach((carousel) => {
    const track = carousel.querySelector(".screenshot-track");
    const prevButton = carousel.querySelector(".carousel-btn.prev");
    const nextButton = carousel.querySelector(".carousel-btn.next");

    if (!track || !prevButton || !nextButton) {
      return;
    }

    const getStep = () => {
      const firstSlide = track.querySelector(".shot-link");
      if (!firstSlide) {
        return Math.max(220, track.clientWidth * 0.85);
      }
      return firstSlide.getBoundingClientRect().width + 10;
    };

    const updateButtons = () => {
      const maxOffset = track.scrollWidth - track.clientWidth - 1;
      const noOverflow = maxOffset <= 0;

      carousel.classList.toggle("is-static", noOverflow);

      prevButton.disabled = noOverflow || track.scrollLeft <= 1;
      nextButton.disabled = noOverflow || track.scrollLeft >= maxOffset;
    };

    prevButton.addEventListener("click", () => {
      track.scrollBy({ left: -getStep(), behavior: "smooth" });
    });

    nextButton.addEventListener("click", () => {
      track.scrollBy({ left: getStep(), behavior: "smooth" });
    });

    track.addEventListener(
      "scroll",
      () => {
        scheduleUpdate(updateButtons);
      },
      { passive: true }
    );

    window.addEventListener("resize", updateButtons);
    updateButtons();
  });
};

const updateStats = () => {
  const androidCount = apps.filter((app) => app.androidUrl).length;
  const iosCount = apps.filter((app) => app.iosUrl).length;

  if (statTotal) {
    statTotal.textContent = String(apps.length);
  }
  if (statAndroid) {
    statAndroid.textContent = String(androidCount);
  }
  if (statIos) {
    statIos.textContent = String(iosCount);
  }
};

if (yearNode) {
  yearNode.textContent = new Date().getFullYear();
}

if (syncDate) {
  syncDate.textContent = formatSyncDate();
}

updateStats();
renderApps();
setupCarousels();

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.16 }
  );

  revealNodes.forEach((node) => observer.observe(node));
} else {
  revealNodes.forEach((node) => node.classList.add("is-visible"));
}
